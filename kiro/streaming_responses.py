"""
Streaming logic for converting Kiro stream to OpenAI Responses API format.

The Responses API SSE protocol is more verbose than Chat Completions: each
logical output (reasoning / message text / function call) is wrapped in an
"item" lifecycle (added -> content parts / deltas -> done) and the stream is
bookended by `response.created` and `response.completed`.

This module implements a small state machine over the unified KiroEvent stream:
- thinking events   -> a `reasoning` item with summary text deltas
- content events    -> a `message` item with output_text deltas
- tool_use events   -> one `function_call` item each (emitted at stream end)

IMPORTANT (retry safety): `response.created` is emitted lazily, only after the
first KiroEvent arrives. parse_kiro_stream raises FirstTokenTimeoutError BEFORE
yielding anything, so on a first-token retry no events have been sent yet and
the retried attempt starts cleanly.
"""

